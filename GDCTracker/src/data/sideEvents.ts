const CATEGORY_ICONS: Record<SideEvent['category'], string> = {
  party: 'Party',
  meetup: 'Meetup',
  showcase: 'Showcase',
  mixer: 'Mixer',
  awards: 'Awards',
  workshop: 'Workshop',
}

/**
 * Convert side events to Session objects so they integrate with existing views.
 * Uses 'Special Event' track type for compatibility.
 */
export function sideEventsToSessions(events: SideEvent[]): Session[] {
  return events.map(e => ({
    id: e.id,
    title: e.title,
    description: `${e.description}\n\nHost: ${e.host}\nVenue: ${e.venue}${e.free ? '\nFree event' : '\nTicket required'}\n\nRSVP: ${e.rsvpUrl}`,
    speakers: [e.host],
    track: 'Special Event' as const,
    format: 'Special Event' as const,
    day: e.day,
    startTime: e.startTime,
    endTime: e.endTime,
    room: e.venue,
    tags: ['side-event', e.category, ...(e.free ? ['free'] : []), CATEGORY_ICONS[e.category]],
  }))
}
